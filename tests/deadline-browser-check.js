const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  const page = await browser.newPage({viewport: {width: 360, height: 800}, timezoneId: 'Asia/Shanghai'}), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install({time: new Date('2026-10-22T16:40:00+08:00')});
  await page.goto('http://127.0.0.1:8766/');
  await page.locator('.q1 .add-button').click();
  await page.locator('#task-text').fill('下周五十三点做班务作业');
  assert.equal(await page.locator('#task-due').inputValue(), '2026-10-30', 'typing recognizes next calendar Friday');
  assert.match(await page.locator('#date-recognition').innerText(), /2026\/10\/30 13:00/);
  await page.screenshot({path: path.resolve(__dirname, '../qa/deadline-recognition-phone.png')});
  await page.locator('#save-task').click();
  assert.match(await page.locator('.q1 .due').innerText(), /10\/30 13:00/);
  await page.reload();
  await page.locator('.q1 .task-open').click();
  await page.clock.setSystemTime(new Date('2026-10-26T10:00:00+08:00'));
  await page.locator('#task-text').fill('下周五十三点做班务作业，带好教材');
  assert.equal(await page.locator('#task-due').inputValue(), '2026-10-30', 'editing existing text does not move saved relative deadline');
  await page.locator('#header-save').click();
  let state = await page.evaluate(() => JSON.parse(localStorage.getItem('fufu-list.v1')));
  assert.equal(state.tasks[0].due, '2026-10-30');
  assert.equal(state.tasks[0].time, '13:00');

  await page.clock.setSystemTime(new Date('2026-10-22T16:40:00+08:00'));
  await page.locator('.q2 .add-button').click();
  await page.locator('#task-text').fill('明天下午两点开会');
  assert.match(await page.locator('#open-date').innerText(), /2026\/10\/23 14:00/);
  await page.locator('#task-text').fill('明天下午2点半开会');
  assert.match(await page.locator('#open-date').innerText(), /14:30/);
  await page.locator('#task-text').fill('稍后再安排开会');
  assert.equal(await page.locator('#task-due').inputValue(), '', 'removing the time phrase removes its automatic deadline');
  await page.locator('#task-text').fill('周6中午开会');
  await page.locator('#open-date').click();
  await page.locator('[data-day="2026-10-29"]').click();
  await page.locator('#calendar-confirm').click();
  await page.locator('#task-text').fill('明天下午两点开会');
  assert.equal(await page.locator('#task-due').inputValue(), '2026-10-29', 'manual calendar date wins');
  await page.reload();
  assert.equal(await page.locator('#task-due').inputValue(), '2026-10-29', 'manual override survives draft recovery');
  await page.locator('#use-recognized-date').click();
  assert.match(await page.locator('#open-date').innerText(), /2026\/10\/23 14:00/);
  await page.locator('#save-task').click();

  await page.locator('.q3 .add-button').click();
  await page.locator('#task-text').fill('明天13:00到15:00开会');
  assert.equal(await page.locator('#task-due').inputValue(), '');
  assert.match(await page.locator('#date-recognition').innerText(), /手动选择/);
  await page.locator('#task-text').fill('下午交报告');
  await page.locator('#clear-date').click();
  await page.locator('#task-text').fill('下午交报告终稿');
  await page.locator('#save-task').click();
  state = await page.evaluate(() => JSON.parse(localStorage.getItem('fufu-list.v1')));
  assert.deepEqual(state.tasks.map(task => [task.due, task.time]), [['2026-10-30', '13:00'], ['2026-10-23', '14:00'], ['', '']]);
  assert.equal(state.tasks[0].text, '下周五十三点做班务作业，带好教材', 'original task text stays intact');
  await page.locator('.q3 .task-open').click();
  await page.locator('#header-save').click();
  state = await page.evaluate(() => JSON.parse(localStorage.getItem('fufu-list.v1')));
  assert.equal(state.tasks[2].due, '', 'reopening a saved task never restores a manually cleared deadline');
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: offline text recognition, preview, save/reload, manual override/recovery, explicit apply and ambiguous times');
})().catch(error => { console.error(error); process.exit(1); });
