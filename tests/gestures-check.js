const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  const context = await browser.newContext({viewport: {width: 360, height: 800}, isMobile: true, hasTouch: true});
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install({time: new Date('2026-10-22T12:00:00+08:00')});
  const touch = await context.newCDPSession(page);
  const qa = path.resolve(__dirname, '../qa'); fs.mkdirSync(qa, {recursive: true});
  await page.goto('http://127.0.0.1:8766/');
  await page.locator('.q1 .add-button').click();
  await page.locator('#task-text').fill('电磁场作业，检查日期和附件');
  await page.locator('#open-date').click();
  await page.locator('[data-day="2026-10-29"]').click();
  await page.locator('#open-time').click();
  await page.locator('#hour-wheel [data-value="18"]').nth(1).click(); await page.locator('#minute-wheel [data-value="30"]').nth(1).click();
  await page.locator('#time-confirm').click();
  await page.locator('#calendar-confirm').click();
  await page.locator('#web-image-input').setInputFiles({name: 'test.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64')});
  await page.waitForFunction(() => document.querySelectorAll('.draft-picture').length === 1);
  await page.locator('#save-task').click();
  await page.locator('.q1 .add-button').click();
  await page.locator('#task-text').fill('这条待办需要保留');
  await page.locator('#save-task').click();
  await page.locator('.q1 .task-open').first().click();
  assert.equal(await page.locator('#open-priority').count(), 1, 'priority opens the custom four-cell sheet');
  await page.locator('#open-priority').click();
  assert.equal(await page.locator('#priority-layer').isVisible(), true);
  assert.equal(await page.getByRole('radio').count(), 4);
  assert.equal(await page.locator('[data-priority="1"]').getAttribute('aria-checked'), 'true');
  const colors = await page.locator('.priority-symbol i.active').evaluateAll(dots => dots.map(dot => getComputedStyle(dot).backgroundColor));
  assert.equal(new Set(colors).size, 4, 'four priority cells use four different colors');
  await page.screenshot({path: path.join(qa, 'priority-sheet-phone.png')});
  await page.locator('[data-priority="2"]').click();
  assert.equal(await page.locator('#priority-layer').isVisible(), false);
  assert.equal(await page.locator('#task-quadrant').inputValue(), '2');
  assert.equal(await page.locator('.q2 .task').count(), 0, 'priority remains a draft until Save');
  await page.locator('#header-save').click();
  assert.equal(await page.locator('.q2 .task').count(), 1);
  assert.match(await page.locator('.q2 .due').innerText(), /10\/29 18:30/);
  assert.equal(await page.locator('.q2 .task-images img').count(), 1);
  await page.locator('.q2 .task-open').click();
  await page.locator('#open-priority').click();
  await page.evaluate(() => window.handleBack());
  assert.equal(await page.locator('#priority-layer').isVisible(), false);
  assert.equal(await page.locator('#editor-layer').isVisible(), true);
  assert.equal(await page.locator('#task-quadrant').inputValue(), '2');
  await page.locator('#cancel').click();

  async function swipe(row, dx, dy = 0) {
    const box = await row.boundingBox();
    const startX = dx < 0 ? box.x + box.width - 16 : box.x + 18;
    const startY = box.y + Math.min(box.height / 2, 40);
    await touch.send('Input.dispatchTouchEvent', {type: 'touchStart', touchPoints: [{x: startX, y: startY}]});
    for (let step = 1; step <= 6; step++) await touch.send('Input.dispatchTouchEvent', {type: 'touchMove', touchPoints: [{x: startX + dx * step / 6, y: startY + dy * step / 6}]});
    await touch.send('Input.dispatchTouchEvent', {type: 'touchEnd', touchPoints: []});
  }
  const first = page.locator('.q2 .task');
  await swipe(first, -90);
  assert.equal(await first.locator('.swipe-delete').isVisible(), true, 'left swipe reveals the right delete button');
  assert.equal(await page.locator('#editor-layer').isVisible(), false, 'a swipe must not also open the task');
  assert.equal(await page.locator('#image-viewer').isVisible(), false);
  assert.equal(await page.locator('.task').count(), 2, 'a swipe alone never deletes');
  await page.clock.runFor(60000);
  assert.equal(await first.locator('.swipe-delete').isVisible(), true, 'deadline refresh must not close a revealed delete button');
  await page.screenshot({path: path.join(qa, 'swipe-delete-phone.png')});
  page.once('dialog', dialog => dialog.dismiss());
  await first.locator('.swipe-delete').click();
  assert.equal(await page.locator('.task').count(), 2, 'cancel keeps the task');
  page.once('dialog', dialog => dialog.accept());
  await first.locator('.swipe-delete').click();
  assert.equal(await page.locator('.q2 .task').count(), 0);
  assert.equal(await page.locator('.q1 .task-title').innerText(), '这条待办需要保留');
  await page.reload();
  assert.equal(await page.locator('.task').count(), 1, 'confirmed deletion persists');
  const remaining = page.locator('.q1 .task');
  await swipe(remaining, 70);
  assert.equal(await remaining.locator('.swipe-delete').isVisible(), false, 'right swipe does not reveal deletion');
  assert.equal(await page.locator('#editor-layer').isVisible(), false);
  await swipe(remaining, 0, 90);
  assert.equal(await remaining.locator('.swipe-delete').isVisible(), false, 'vertical scroll does not reveal deletion');
  await swipe(remaining, -90);
  assert.equal(await remaining.locator('.swipe-delete').isVisible(), true);
  assert.equal(await page.evaluate(() => window.handleBack()), true);
  assert.equal(await remaining.locator('.swipe-delete').isVisible(), false, 'Back closes swipe actions before leaving the app');
  await swipe(remaining, -90);
  await page.locator('h1').click();
  assert.equal(await remaining.locator('.swipe-delete').isVisible(), false, 'outside tap closes swipe actions');
  await remaining.locator('.task-open').click();
  assert.equal(await page.locator('#editor-layer').isVisible(), true, 'normal task tap still opens editing');
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: custom priority grid; selected state; date/image retention; left swipe; cancel/confirm/persist deletion; scroll/tap handling');
})().catch(error => { console.error(error); process.exit(1); });
