const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  const context = await browser.newContext({viewport: {width: 360, height: 800}, isMobile: true, hasTouch: true});
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.clock.install({time: new Date('2026-10-22T12:00:00+08:00')});
  await page.goto('http://127.0.0.1:8766/');
  await page.locator('.q1 .add-button').click();
  await page.locator('#task-text').fill('滚轮设置截止时间');
  await page.locator('#open-date').click();
  await page.locator('[data-day="2026-10-29"]').click();
  assert.equal(await page.locator('#open-time').count(), 1, 'time opens a two-column wheel');
  await page.locator('#open-time').click();
  assert.equal(await page.locator('#time-layer').isVisible(), true);
  await page.locator('#hour-wheel [data-value="18"]').nth(1).click();
  await page.locator('#minute-wheel [data-value="30"]').nth(1).click();
  await page.screenshot({path: path.resolve(__dirname, '../qa/time-wheel-phone.png')});
  await page.locator('#time-confirm').click();
  assert.equal(await page.locator('#calendar-time').inputValue(), '18:30');
  await page.locator('#calendar-confirm').click();
  await page.locator('#save-task').click();
  assert.match(await page.locator('.q1 .due').innerText(), /18:30/);
  await page.reload();
  assert.match(await page.locator('.q1 .due').innerText(), /18:30/);
  await page.locator('.q1 .task-open').click();
  await page.locator('#open-date').click();
  await page.locator('#open-time').click();
  await page.locator('#hour-wheel [data-value="0"]').nth(1).click();
  await page.locator('#minute-wheel [data-value="0"]').nth(1).click();
  await page.locator('#time-cancel').click();
  assert.equal(await page.locator('#calendar-time').inputValue(), '18:30', 'cancel preserves prior value');
  await page.locator('#open-time').click();
  assert.equal(await page.evaluate(() => window.handleBack()), true);
  assert.equal(await page.locator('#calendar-layer').isVisible(), true);
  assert.equal(await page.locator('#time-layer').isVisible(), false);
  await page.locator('#open-time').click();
  await page.locator('#hour-wheel [data-value="23"]').nth(1).click();
  await page.locator('#minute-wheel [data-value="59"]').nth(1).click();
  await page.locator('#time-confirm').click();
  assert.equal(await page.locator('#calendar-time').inputValue(), '23:59');
  await page.locator('#open-time').click();
  await page.locator('#time-clear').click();
  assert.equal(await page.locator('#calendar-time').inputValue(), '');
  await page.locator('#calendar-confirm').click();
  await page.locator('#header-save').click();
  assert.doesNotMatch(await page.locator('.q1 .due').innerText(), /\d{2}:\d{2}/);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: hour/minute wheels; 18:30 and 23:59; cancel/back; clear; saved deadline persistence');
})().catch(e => { console.error(e); process.exit(1); });
