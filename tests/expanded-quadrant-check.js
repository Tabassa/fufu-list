const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  const page = await browser.newPage({viewport: {width: 360, height: 800}, timezoneId: 'Asia/Shanghai'}), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install({time: new Date('2026-10-23T12:00:00+08:00')});
  await page.goto('http://127.0.0.1:8766/');
  const longText = '学生报告：信号与系统课程，五分钟以内，准备演示材料并核对实验结果。'.repeat(8);
  await page.evaluate(text => {
    const C = window.FufuCore, state = C.createState(), image = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=';
    C.saveTask(state, {text, quadrant: 1, due: '2026-10-30', time: '13:00', images: [image]});
    for (let i = 2; i <= 8; i++) C.saveTask(state, {text: '第一象限待办 ' + i, quadrant: 1, due: '2026-11-02'});
    C.saveTask(state, {text: '第二象限待办', quadrant: 2});
    C.saveTask(state, {text: '第三象限待办', quadrant: 3});
    localStorage.setItem('fufu-list.v1', C.serialize(state));
  }, longText);
  await page.reload();
  const type = await page.locator('.q1 .task-title').first().evaluate(element => parseFloat(getComputedStyle(element).fontSize));
  assert.ok(type < 15, 'overview task type is smaller than the previous 15px');
  assert.ok(await page.locator('.q1 h2').evaluate(element => parseFloat(getComputedStyle(element).fontSize)) < 14);
  await page.screenshot({path: path.resolve(__dirname, '../qa/smaller-type-phone.png')});
  await page.locator('.q1 .quad-body').evaluate(body => { body.scrollTop = 60; });
  const originalScroll = await page.locator('.q1 .quad-body').evaluate(body => body.scrollTop);
  await page.locator('.q1 .quadrant-symbol').click();
  assert.equal(await page.locator('#board.expanded').count(), 1, 'quadrant icon opens the full-screen list');
  assert.equal(await page.locator('#board .quad').count(), 1);
  assert.equal(await page.locator('#board .quad').getAttribute('data-quadrant'), '1');
  assert.equal(await page.locator('#board .task').count(), 8);
  const bounds = await page.locator('#board .quad').boundingBox();
  assert.ok(bounds.width > 320 && bounds.height > 740, 'the original colored quadrant fills the app screen');
  const preview = await page.locator('.task[data-id="1"] .task-title').evaluate(element => ({height: element.clientHeight, lineHeight: parseFloat(getComputedStyle(element).lineHeight)}));
  assert.ok(preview.height > preview.lineHeight * 2 && preview.height <= preview.lineHeight * 4 + 1, 'full-screen preview shows up to four lines');
  assert.equal(await page.locator('.task img').count(), 0, 'photos remain inside task details');
  await page.screenshot({path: path.resolve(__dirname, '../qa/expanded-quadrant-phone.png')});
  await page.locator('.task[data-id="1"] .task-open').click();
  assert.equal(await page.locator('#task-text').inputValue(), longText);
  assert.equal(await page.locator('.draft-picture').count(), 1);
  await page.evaluate(() => window.handleBack());
  assert.equal(await page.locator('#editor-layer').isVisible(), false);
  assert.equal(await page.locator('#board.expanded').count(), 1, 'back from a task returns to its full-screen quadrant');
  await page.locator('.task[data-id="1"] .check').click();
  assert.equal(await page.locator('.task[data-id="1"]').evaluate(element => element.classList.contains('done')), true);
  await page.locator('.task[data-id="1"] .check').click();
  await page.locator('#quadrant-back').click();
  assert.equal(await page.locator('#board .quad').count(), 4);
  assert.ok(Math.abs(await page.locator('.q1 .quad-body').evaluate(body => body.scrollTop) - originalScroll) < 2, 'return restores overview scroll');
  await page.locator('.q2 h2').click();
  assert.equal(await page.locator('#board .quad').getAttribute('data-quadrant'), '2', 'the title also opens the quadrant');
  await page.evaluate(() => window.handleBack());
  await page.locator('.q3 .quad-heading').click({position: {x: 2, y: 20}});
  assert.equal(await page.locator('#board .quad').getAttribute('data-quadrant'), '3', 'colored header space is clickable');
  await page.locator('#quadrant-back').click();
  await page.locator('.q4 .add-button').click();
  assert.equal(await page.locator('#task-quadrant').inputValue(), '4');
  assert.equal(await page.locator('#board.expanded').count(), 0, 'plus adds without opening the quadrant');
  await page.locator('#cancel').click();
  await page.locator('.q4 h2').click();
  assert.equal(await page.locator('.quad-body .empty').count(), 1, 'an empty quadrant also expands');
  await page.locator('.add-button').click();
  assert.equal(await page.locator('#task-quadrant').inputValue(), '4');
  await page.locator('#task-text').fill('全屏新增待办'); await page.locator('#save-task').click();
  assert.equal(await page.locator('#board.expanded').count(), 1);
  assert.equal(await page.locator('#board .task').count(), 1);
  await page.locator('#board .task-open').click();
  await page.locator('#open-priority').click(); await page.locator('[data-priority="2"]').click(); await page.locator('#header-save').click();
  assert.equal(await page.locator('#board .task').count(), 0, 'moving a task updates the focused quadrant');
  await page.locator('#quadrant-back').click();
  assert.equal(await page.locator('.q2 .task').count(), 2);
  await page.setViewportSize({width: 360, height: 800});
  await page.locator('.q3 h2').click();
  const front = page.locator('.task-front'), box = await front.boundingBox();
  await page.mouse.move(box.x + box.width - 15, box.y + 30); await page.mouse.down();
  await page.mouse.move(box.x + box.width - 100, box.y + 30, {steps: 8}); await page.mouse.up();
  assert.equal(await page.locator('.swipe-delete').isVisible(), true, 'left swipe also reveals delete inside the full-screen list');
  page.once('dialog', dialog => dialog.dismiss()); await page.locator('.swipe-delete').click();
  assert.equal(await page.locator('#board .task').count(), 1);
  page.once('dialog', dialog => dialog.accept()); await page.locator('.swipe-delete').click();
  assert.equal(await page.locator('#board .task').count(), 0);
  assert.equal(await page.locator('#board.expanded').count(), 1);
  await page.locator('#quadrant-back').click();
  for (const viewport of [{width: 320, height: 568}, {width: 800, height: 1280}, {width: 1280, height: 800}]) {
    await page.setViewportSize(viewport); await page.locator('.q1 h2').click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), viewport.width);
    const rows = await page.locator('.task').evaluateAll(elements => elements.map(element => element.getBoundingClientRect().height));
    assert.ok(rows.every(height => Math.abs(height - rows[0]) < 1), 'expanded rows stay equal height');
    await page.locator('#quadrant-back').click();
  }
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: smaller overview type; all four full-screen quadrants; title/icon/header clicks; independent plus; four-line previews; return, editing, completion and priority moves');
})().catch(error => { console.error(error); process.exit(1); });
